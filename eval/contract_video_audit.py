"""Audit a deterministic contract-rendered MP4 against its teaching timeline.

This checks the code-rendered baseline only. It is not a semantic evaluator for
videos generated by a stochastic model.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2
import numpy as np

from generation.contract_video import compile_contract_video_plan
from generation.teaching_contract import load_contracts


def _phase(index: int, setup_count: int, motion_count: int) -> str:
    if index < setup_count:
        return "setup"
    if index < setup_count + motion_count:
        return "motion"
    return "result"


def audit_contract_video(video_path: str | Path, contract: dict, case: dict,
                         *, width: int = 832, height: int = 480,
                         fps: int = 24, max_mean_error: float = 15.0) -> dict:
    """Return a phase-aware verdict with timestamps for encoded visual defects."""
    plan = compile_contract_video_plan(contract, case, width=width, height=height, fps=fps)
    references = plan["frames"]
    path = Path(video_path)
    result = {"id": case["id"], "video_path": str(path), "status": "unobservable",
              "reason": None, "expected_frames": len(references), "frames_checked": 0,
              "phase_failures": {"setup": 0, "motion": 0, "result": 0},
              "evidence": []}
    capture = cv2.VideoCapture(str(path))
    try:
        if not capture.isOpened():
            result["reason"] = "video_cannot_open"
            return result
        actual_count = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
        actual_fps = float(capture.get(cv2.CAP_PROP_FPS))
        actual_width = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH))
        actual_height = int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT))
        result.update({"actual_frames": actual_count, "actual_fps": actual_fps,
                       "actual_width": actual_width, "actual_height": actual_height})
        if (actual_count != len(references) or abs(actual_fps - fps) > 0.1
                or (actual_width, actual_height) != (width, height)):
            result["reason"] = "video_metadata_mismatch"
            return result
        failures = []
        setup = plan["setup_frame"]
        for index, reference in enumerate(references):
            ok, frame = capture.read()
            if not ok or frame is None or frame.shape != reference.shape:
                result["reason"] = "frame_decode_failed"
                result["evidence"] = [{"frame_index": index, "time_s": round(index / fps, 3),
                                       "phase": _phase(index, plan["setup_frames"], plan["motion_frames"]),
                                       "reason": "frame_decode_failed"}]
                return result
            result["frames_checked"] += 1
            phase = _phase(index, plan["setup_frames"], plan["motion_frames"])
            # Score on the reference ink as well as the whole canvas. Without
            # this mask, missing a small formula on a white slide looks "close".
            reference_ink = np.any(reference < 235, axis=2)
            changed = np.any(cv2.absdiff(reference, setup) > 20, axis=2)
            mask = reference_ink | changed
            diff = cv2.absdiff(frame, reference)
            mean_error = float(np.mean(diff[mask])) if np.any(mask) else float(np.mean(diff))
            if mean_error > max_mean_error:
                setup_diff = cv2.absdiff(frame, setup)
                setup_error = float(np.mean(setup_diff[mask])) if np.any(mask) else float(np.mean(setup_diff))
                failures.append({"frame_index": index, "time_s": round(index / fps, 3),
                                 "phase": phase, "mean_error": round(mean_error, 3),
                                 "setup_mean_error": round(setup_error, 3)})
                result["phase_failures"][phase] += 1
        if not failures:
            result.update({"status": "pass", "reason": "all_frames_match"})
            return result
        result_failures = [item for item in failures if item["phase"] == "result"]
        setup_like = [item for item in result_failures
                      if item["setup_mean_error"] < item["mean_error"] * 0.5]
        missing = (len(result_failures) >= plan["result_frames"] * 0.5
                   and len(setup_like) >= len(result_failures) * 0.8)
        result["status"] = "missing" if missing else "wrong"
        result["reason"] = ("result_remains_at_setup" if missing
                            else "frames_differ_from_contract")
        first_by_phase = {}
        for item in failures:
            first_by_phase.setdefault(item["phase"], item)
        evidence = list(first_by_phase.values())
        worst = max(failures, key=lambda item: item["mean_error"])
        if worst not in evidence:
            evidence.append(worst)
        result["evidence"] = evidence
        return result
    finally:
        capture.release()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--video", type=Path, required=True)
    parser.add_argument("--case-id", required=True)
    parser.add_argument("--contracts", type=Path,
                        default=Path("data/teaching_contracts/examples.jsonl"))
    parser.add_argument("--prompts", type=Path,
                        default=Path("data/prompts/pilot_v0_1.jsonl"))
    args = parser.parse_args()
    contracts = load_contracts(args.contracts)
    cases = (json.loads(line) for line in args.prompts.read_text(encoding="utf-8").splitlines()
             if line.strip())
    case = next((item for item in cases if item.get("id") == args.case_id), None)
    if args.case_id not in contracts or case is None:
        parser.error(f"unknown case-id: {args.case_id}")
    report = audit_contract_video(args.video, contracts[args.case_id], case)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    if report["status"] != "pass":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
