"""Compute per-case correlation between standard eval (mean_agg) and TeachQuiz-T (NG).

This tests the key hypothesis: standard eval scores correlate weakly or
negatively with actual learning gain (TeachQuiz-T).

Usage:
    python scripts/eval_vs_teachquiz_correlation.py
"""
from __future__ import annotations
import json
from pathlib import Path


EVAL_5B = "/data/zyf/rise-teacher/outputs/eval_pilot_v0_1/per_case.jsonl"
EVAL_13B = "/data/zyf/rise-teacher/outputs/eval_pilot_v0_1_wan13b/per_case.jsonl"
TQ_5B = "/data/zyf/rise-teacher/outputs/teachquiz_5b_qwen3vl_autoprobe/per_case.jsonl"
TQ_13B = "/data/zyf/rise-teacher/outputs/teachquiz_13b_qwen3vl_autoprobe/per_case.jsonl"


def load_jsonl(path: str) -> list[dict]:
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def pearson(xs: list[float], ys: list[float]) -> float:
    n = len(xs)
    if n < 2:
        return float("nan")
    mx = sum(xs) / n
    my = sum(ys) / n
    num = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    dx = (sum((x - mx) ** 2 for x in xs) ** 0.5)
    dy = (sum((y - my) ** 2 for y in ys) ** 0.5)
    return num / (dx * dy) if dx * dy > 0 else float("nan")


def analyze(model_label: str, eval_path: str, tq_path: str) -> dict:
    eval_rows = {r["id"]: r for r in load_jsonl(eval_path)}
    tq_rows = {r["id"]: r for r in load_jsonl(tq_path) if r.get("valid")}

    shared_ids = sorted(set(eval_rows) & set(tq_rows))
    eval_scores = [float(eval_rows[i].get("aggregate_score", 0) or 0) for i in shared_ids]
    ng_scores = [float(tq_rows[i]["normalized_gain"]) for i in shared_ids]
    lg_scores = [float(tq_rows[i]["learning_gain"]) for i in shared_ids]

    r_ng = pearson(eval_scores, ng_scores)
    r_lg = pearson(eval_scores, lg_scores)

    # Per-dim correlations — scores are nested dicts with 'score' key
    SKIP_KEYS = {"id", "discipline", "task_type", "aggregate_score",
                 "video_path", "prompt", "difficulty", "strict_pass"}
    all_dims = sorted({k for r in eval_rows.values() for k in r.keys()
                       if k not in SKIP_KEYS and not k.startswith("_")
                       and isinstance(r.get(k), dict) and "score" in (r.get(k) or {})})
    dim_corr_ng = {}
    for d in all_dims:
        xs = [float((eval_rows[i].get(d) or {}).get("score", 0) or 0) for i in shared_ids]
        if len(set(xs)) < 2:
            continue
        dim_corr_ng[d] = round(pearson(xs, ng_scores), 3)

    return {
        "model": model_label,
        "n": len(shared_ids),
        "r_eval_ng": round(r_ng, 3),
        "r_eval_lg": round(r_lg, 3),
        "per_dim": dim_corr_ng,
    }


def main() -> None:
    results = []
    for label, ep, tp in [
        ("Wan5B", EVAL_5B, TQ_5B),
        ("Wan1.3B", EVAL_13B, TQ_13B),
    ]:
        try:
            res = analyze(label, ep, tp)
            results.append(res)
            print(f"{label}: n={res['n']}, r(eval,NG)={res['r_eval_ng']}, "
                  f"r(eval,LG)={res['r_eval_lg']}")
            print(f"  per-dim: {res['per_dim']}")
        except Exception as e:
            print(f"{label}: error — {e}")

    lines = ["# Standard Eval vs TeachQuiz-T Correlation\n"]
    lines.append("Does a higher standard eval score predict higher student learning gain?\n")
    lines.append("| Model | N | r(agg, NG) | r(agg, LG) |")
    lines.append("|---|---|---|---|")
    for r in results:
        lines.append(f"| {r['model']} | {r['n']} | {r['r_eval_ng']} | {r['r_eval_lg']} |")

    lines.append("\n## Per-dimension correlation with NG\n")
    all_dims = sorted({d for r in results for d in r["per_dim"]})
    lines.append("| Dim | " + " | ".join(r["model"] for r in results) + " |")
    lines.append("|---|" + "|".join(["---"] * len(results)) + "|")
    for d in all_dims:
        row = [d] + [str(r["per_dim"].get(d, "—")) for r in results]
        lines.append("| " + " | ".join(row) + " |")

    lines.append("\n## Interpretation\n")
    for r in results:
        rng = r["r_eval_ng"]
        if abs(rng) < 0.1:
            interp = "negligible"
        elif abs(rng) < 0.3:
            interp = "weak"
        elif abs(rng) < 0.5:
            interp = "moderate"
        else:
            interp = "strong"
        direction = "positive" if rng > 0 else "negative"
        r2_pct = rng ** 2 * 100
        lines.append(f"- **{r['model']}**: r={rng} ({direction}, {interp}), "
                     f"r²={r2_pct:.1f}% explained variance — "
                     f"standard eval {'poorly' if abs(rng) < 0.3 else ''} predicts student learning")

    lines.append("\n_Generated by scripts/eval_vs_teachquiz_correlation.py_")
    out = Path("analysis/eval_vs_teachquiz_corr.md")
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
